#!/usr/bin/env node
'use strict';
/**
 * 生成法规标准符合性自查样例（可再生）。用法：node scripts/make-sample.js --out <dir> [--seed <n>]
 *
 * **样例中的「标准名称」「条款编号」「条款原文」全部为虚构，不对应任何真实法规与标准。**
 * 本技能不从记忆中引用条款，样例条款仅用于验证脚本的解析与对照逻辑。
 *
 * seed 改变虚构文号与措辞细节，但预期结论不变：
 *   sample-rules.xlsx（12 条）配 sample-materials.xlsx 恒为：
 *   6 条已见对应材料、2 条未见对应材料、2 条材料不完整、2 条需进一步确认、1 份未对应材料。
 */
const fs = require('fs');
const path = require('path');
const { writeXlsx } = require('./lib/xlsx-lite');
const C = require('./lib/common');

const a = C.parseArgs(process.argv.slice(2), ['out', 'seed'], []);
const out = a.out || path.join(__dirname, '..', 'examples');
const seed = a.seed ? Number(a.seed) : 1;
let s = seed * 7919 + 13;
const rnd = () => ((s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
const no = () => String(100 + Math.floor(rnd() * 800));
const pick = (arr) => arr[Math.floor(rnd() * arr.length) % arr.length];

fs.mkdirSync(out, { recursive: true });

/* 虚构标准名称：刻意用「XX/T 9xxx—20XX（虚构）」形式，避免与任何真实标准编号相混 */
const STD_A = `XX/T 9${no()}—2026《炼化装置设备管理要求》（本样例虚构标准，非真实标准）`;
const STD_B = `XXG ${no()}—2026《特种设备使用单位管理规定》（本样例虚构规定，非真实法规）`;
/* 虚构企业制度：演示集团/公司制度与法规标准同一口径走 --rules；编号按口径对照写 Q/XX-虚构-00N */
const STD_C = `Q/XX-虚构-00${1 + Math.floor(rnd() * 9)}《公司设备管理规定》（本样例虚构企业制度，非真实制度）`;

/* ---------------- 主条款清单：12 条（条款编号与原文均为虚构） ----------------
 * 已见对应材料 6 条：1（制度）、2（台账）、3（巡检）、5（检修）、8（培训持证）、10（应急演练）
 * 材料不完整 2 条：4（技术档案，自报缺页）、7（安全阀校验，自报仅覆盖部分）
 * 未见对应材料 2 条：6（定期检验报告）、9（隐患排查治理记录）
 * 需进一步确认 2 条：11（「应当健全有效」纯原则性表述）、12（「必要时采取相应措施」）
 */
writeXlsx(path.join(out, 'sample-rules.xlsx'), {
  '条款清单': [
    [`${pick(['某某', '某'])}炼化公司 设备管理条款自查清单（虚构样例，条款编号与原文均为虚构，不对应任何真实法规标准）`],
    [],
    ['条款编号', '条款原文', '应做事项', '标准名称'],
    ['第一条', '使用单位应当建立设备管理制度，明确各岗位的设备管理职责。', '建立设备管理制度并明确岗位职责', STD_A],
    ['第二条', '使用单位应当建立设备台账，逐台登记设备的基本参数与运行状态。', '建立设备台账', STD_A],
    ['第三条', '使用单位应当组织开展日常巡检，并如实记录巡检情况。', '开展巡检并保留巡检记录', STD_A],
    ['第四条', '使用单位应当为每台设备建立技术档案，随机资料应当归档保存。', '建立设备技术档案', STD_A],
    ['第五条', '使用单位应当按计划组织设备检修，并保留检修记录。', '开展检修并保留检修记录', STD_A],
    ['第六条', '压力容器应当按规定周期申报定期检验，并保存定期检验报告。', '申报定期检验并保存检验报告', STD_B],
    ['第七条', '安全阀应当按规定周期校验，校验后加装铅封并保存校验记录。', '安全阀按期校验并保存校验记录', STD_B],
    ['第八条', '设备操作与维修人员应当经培训考核合格后持证上岗，并保存培训与持证记录。', '人员培训考核并保存持证记录', STD_B],
    ['第九条', '使用单位应当开展设备隐患排查治理，建立隐患登记与治理台账。', '开展隐患排查治理并建立台账', STD_C],
    ['第十条', '使用单位应当制定设备事故应急预案，并按计划组织应急演练。', '制定应急预案并组织演练', STD_B],
    ['第十一条', '使用单位的设备管理工作应当健全有效，并持续加强。', '（条款未指明具体资料）', STD_C],
    ['第十二条', '必要时，使用单位应当采取相应措施，妥善处置有关情况。', '（条款未指明具体资料）', STD_A],
  ],
});

/* ---------------- 主资料清单 ----------------
 * 与上表对应：制度/台账/巡检/检修/培训持证/应急演练 6 项齐备；
 * 技术档案与安全阀校验自报不完整；定期检验报告与隐患台账完全没有；
 * 班组考勤统计表对不上任何条款。
 */
writeXlsx(path.join(out, 'sample-materials.xlsx'), {
  '资料清单': [
    ['资料名称', '资料类型', '存放位置', '完整性说明', '备注'],
    [`常减压车间设备管理制度-${no()}号.docx`, '制度', '车间资料柜A-1', '', ''],
    ['常减压车间设备台账2026.xlsx', '台账', '车间资料柜A-2', '', ''],
    ['2026年三季度巡检记录汇总.xlsx', '记录', '车间资料柜A-3', '', ''],
    [`设备技术档案-${no()}.pdf`, '档案', '车间资料柜A-4', '缺页，附图部分未归档', '随机资料待补齐'],
    ['设备检修记录台账2026.xlsx', '记录', '车间资料柜B-1', '', ''],
    ['安全阀校验记录.xlsx', '记录', '车间资料柜B-2', '仅有一季度部分，二三季度未归档', ''],
    ['特种作业人员持证上岗台账.xlsx', '台账', '车间资料柜C-1', '', ''],
    ['设备事故应急预案与演练记录2026.docx', '记录', '车间资料柜C-2', '', ''],
    [`班组考勤统计表-${no()}.xlsx`, '', '车间资料柜D-1', '', '与本次自查无关'],
  ],
});

/* ---------------- 变体：笼统条款清单（全部条款都只给原则性表述） ----------------
 * 预期：4 条全部进入 needInterpretation，脚本不自行解释条款含义、不作任何判定。
 */
writeXlsx(path.join(out, 'sample-rules-vague.xlsx'), {
  '条款清单': [
    ['条款编号', '条款原文', '标准名称'],
    ['4.1', '使用单位应当加强管理，确保工作有效开展。', STD_A],
    ['4.2', '必要时应当采取适当措施。', STD_A],
    ['4.3', '相关工作应当健全完善。', STD_A],
    ['4.4', '应当及时妥善处理有关事项。', STD_A],
  ],
});

/* ---------------- 变体：条款齐备、资料齐备（正反对照用） ---------------- */
writeXlsx(path.join(out, 'sample-rules-small.xlsx'), {
  '条款清单': [
    ['条款编号', '条款原文', '应做事项'],
    ['第一条', '使用单位应当建立设备管理制度。', '建立设备管理制度'],
    ['第二条', '使用单位应当建立设备台账。', '建立设备台账'],
    ['第三条', '使用单位应当开展日常巡检并保留巡检记录。', '开展巡检并保留记录'],
  ],
});
writeXlsx(path.join(out, 'sample-materials-complete.xlsx'), {
  '资料清单': [
    ['资料名称', '资料类型', '存放位置', '完整性说明'],
    ['车间设备管理制度.docx', '制度', '资料柜A-1', ''],
    ['车间设备台账.xlsx', '台账', '资料柜A-2', ''],
    ['巡检记录2026全年.xlsx', '记录', '资料柜A-3', ''],
  ],
});

/* ---------------- 变体：资料极少，大量未见对应材料 ---------------- */
writeXlsx(path.join(out, 'sample-materials-sparse.xlsx'), {
  '资料清单': [
    ['资料名称', '资料类型', '存放位置'],
    ['常减压车间设备台账.xlsx', '台账', '资料柜A-1'],
  ],
});

/* ---------------- 变体：Markdown 条款文本（虚构） ---------------- */
fs.writeFileSync(path.join(out, 'sample-rules.md'), [
  `# ${STD_A} 条款摘录（虚构样例）`,
  '',
  '> 本文件的标准名称、条款编号与条款原文**均为虚构**，不对应任何真实法规与标准，仅用于验证脚本解析。',
  '',
  '第一条 使用单位应当建立设备管理制度，明确各岗位的设备管理职责。',
  '第二条 使用单位应当建立设备台账，逐台登记设备基本参数。',
  '第三条 使用单位应当组织开展日常巡检并如实记录。',
  '第四条 使用单位应当开展设备隐患排查治理，建立隐患登记台账。',
  '第五条 使用单位的设备管理工作应当健全有效。',
  '',
  `（文号：设备管理${no()}号，虚构）`,
].join('\n'), 'utf8');

/* ---------------- 变体：厂内制度清单（配 --internal 用） ---------------- */
writeXlsx(path.join(out, 'sample-internal.xlsx'), {
  '制度清单': [
    ['资料名称', '资料类型', '存放位置', '完整性说明'],
    [`厂设备隐患排查治理管理办法-${no()}号.docx`, '制度', '厂办文件柜-1', ''],
    ['厂压力容器定期检验管理规定.docx', '制度', '厂办文件柜-2', ''],
    [`公司设备管理规定（Q/XX-虚构-00${1 + Math.floor(rnd() * 9)}）.docx`, '制度', '公司设备管理部门文件柜-1', ''],
  ],
});

console.log(JSON.stringify({
  ok: true, out, seed,
  note: '样例中的标准名称、条款编号与条款原文均为虚构，不对应任何真实法规与标准',
  files: fs.readdirSync(out).filter((f) => /^sample-.*\.(xlsx|md)$/.test(f)).sort(),
}));
