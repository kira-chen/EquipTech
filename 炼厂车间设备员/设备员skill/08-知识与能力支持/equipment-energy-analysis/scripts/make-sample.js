#!/usr/bin/env node
'use strict';
/**
 * 生成设备能效样例（可再生）。用法：node scripts/make-sample.js --out <dir> [--seed <n>]
 * 主样例恒：6 台离心泵、2 台能效偏低、1 台参数不全（数据不足）、1 台效率超 100%（异常值）、
 *          2 个对比组、含设计参数与单价。seed 变数值抖动变，但各类条数不变。
 */
const fs = require('fs');
const path = require('path');
const { writeXlsx } = require('./lib/xlsx-lite');
const C = require('./lib/common');

const a = C.parseArgs(process.argv.slice(2), ['out', 'seed'], []);
const out = a.out || path.join(__dirname, '..', 'examples');
const seed = a.seed ? Number(a.seed) : 1;
let s = seed * 7919 + 13;
const rnd = () => ((s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
/** 小幅抖动：幅度受控，不改变偏低/正常/数据不足/异常值的归类 */
const j = (base, amp) => Number((base + (rnd() - 0.5) * 2 * amp).toFixed(3));

fs.mkdirSync(out, { recursive: true });

// 泵样例：按 η = ρgQH/3600000 / 轴功率 反推轴功率，保证效率落在期望区间
const G = 9.80665;
const shaftFor = (rho, q, h, eff) => Number((((rho * G * q * h) / 3600000) / eff).toFixed(2));

const runRows = [['设备位号', '设备名称', '设备类型', '分组', '流量', '扬程', '介质密度', '轴功率', '电机功率', '电机效率', '运行时间']];
// 一组：常压塔顶回流泵 A/B/C —— B 明显偏低
runRows.push(['P-1101A', '常压塔顶回流泵A', '离心泵', '回流泵组', j(320, 3), j(95, 0.8), 860, shaftFor(860, 320, 95, 0.78), '', '', 7200]);
runRows.push(['P-1101B', '常压塔顶回流泵B', '离心泵', '回流泵组', j(305, 3), j(93, 0.8), 860, shaftFor(860, 305, 93, 0.61), '', '', 6800]);
runRows.push(['P-1101C', '常压塔顶回流泵C', '离心泵', '回流泵组', j(318, 3), j(94, 0.8), 860, shaftFor(860, 318, 94, 0.76), '', '', 7000]);
// 二组：渣油泵 A/B —— A 偏低（有设计效率作基准）
runRows.push(['P-1102A', '常压渣油泵A', '离心泵', '渣油泵组', j(180, 2), j(120, 1), 940, shaftFor(940, 180, 120, 0.62), '', '', 7400]);
runRows.push(['P-1102B', '常压渣油泵B', '离心泵', '渣油泵组', j(185, 2), j(122, 1), 940, shaftFor(940, 185, 122, 0.77), '', '', 7300]);
// 数据不足：只有电机功率、无电机效率，且缺介质密度 → 参数不全，效率 null
runRows.push(['P-1103A', '循环水泵A', '离心泵', '循环水泵组', j(420, 4), j(38, 0.5), '', '', j(62, 1), '', 8000]);
// 异常值：轴功率填得过小（写成了电流值），算得效率远超 100%
runRows.push(['P-1104A', '柴油出装置泵', '离心泵', '外送泵组', j(150, 2), j(110, 1), 830, j(9.5, 0.2), '', '', 6200]);
runRows.push(['合计', '', '', '', '', '', '', '', '', '', '']);

writeXlsx(path.join(out, 'sample-pump-energy.xlsx'), {
  '运行数据': runRows,
  '设计参数': [
    ['设备位号', '设备名称', '额定流量', '额定扬程', '额定功率', '设计效率'],
    ['P-1102A', '常压渣油泵A', 190, 125, 85, 78],
    ['P-1102B', '常压渣油泵B', 190, 125, 85, 78],
  ],
  '单价': [['能源介质', '单价', '计价单位'], ['电', 0.62, 'kWh']],
});

// 变体：无设计参数、无单价 → 只做同类横向对比，不做偏差分析、不做费用测算
writeXlsx(path.join(out, 'sample-no-design.xlsx'), {
  '运行数据': [
    ['设备位号', '设备名称', '设备类型', '分组', '流量', '扬程', '介质密度', '轴功率', '运行时间'],
    ['P-2101A', '加氢进料泵A', '离心泵', '进料泵组', j(210, 2), j(140, 1), 800, shaftFor(800, 210, 140, 0.75), 7100],
    ['P-2101B', '加氢进料泵B', '离心泵', '进料泵组', j(205, 2), j(138, 1), 800, shaftFor(800, 205, 138, 0.58), 7050],
    ['P-2102A', '独苗泵', '离心泵', '独立泵组', j(90, 1), j(60, 0.5), 810, shaftFor(810, 90, 60, 0.70), 6000],
  ],
});

// 变体：多设备类型混排（风机/压缩机/电机/加热炉/换热器各一台），列名用 SAP PM / EM 导出风格
// （功能位置 / 设备描述 / 对象类型），验证 mergeAliases 后的共享别名
writeXlsx(path.join(out, 'sample-mixed-types.xlsx'), {
  '运行数据': [
    ['功能位置', '设备描述', '对象类型', '分组', '流量', '全压', '轴功率', '进口压力', '出口压力',
      '输出功率', '输入功率', '燃料量', '低位发热值', '有效热负荷', '换热量', '换热面积', '对数平均温差', '运行时间'],
    ['F-1201', '催化主风机', '风机', '风机组', j(48000, 300), j(9800, 50), j(180, 2), '', '', '', '', '', '', '', '', '', '', 7800],
    ['K-1301', '富气压缩机', '压缩机', '压缩机组', j(6000, 50), '', j(520, 5), 0.12, 1.25, '', '', '', '', '', '', '', '', 7600],
    ['M-1401', '主风机电机', '电机', '电机组', '', '', '', '', '', j(1850, 10), j(1960, 10), '', '', '', '', '', '', 7800],
    ['H-1501', '常压加热炉', '加热炉', '加热炉组', '', '', '', '', '', '', '', j(1.85, 0.02), 42000, j(69000, 300), '', '', '', 7900],
    ['E-1601', '原油换热器', '换热器', '换热器组', '', '', '', '', '', '', '', '', '', '', j(3200, 20), 420, j(28, 0.3), 8000],
  ],
});

// 变体：压缩机多变效率口径 + 分时电价
//   K-A：进出口压力/温度/绝热指数齐全 → 多变效率可算
//   K-B：缺出口温度 → --polytropic 时记入数据不足（不按典型 k 或等温口径顶替）
//   K-C：缺绝热指数 → 同上
//   单价表三行峰/平/谷 + 一行加权 → 脚本只认「加权」行；去掉加权行则不测算
writeXlsx(path.join(out, 'sample-compressor-polytropic.xlsx'), {
  '运行数据': [
    ['功能位置', '设备描述', '对象类型', '分组', '流量', '进口压力', '出口压力', '进口温度', '出口温度', '绝热指数', '轴功率', '运行时间'],
    ['K-2101A', '循环氢压缩机A', '压缩机', '循环氢机组', j(5200, 40), 1.60, 2.10, j(40, 0.5), j(78, 0.5), 1.40, j(760, 5), 8000],
    ['K-2101B', '循环氢压缩机B', '压缩机', '循环氢机组', j(5100, 40), 1.60, 2.10, j(41, 0.5), '', 1.40, j(790, 5), 7900],
    ['K-2201', '富气压缩机', '压缩机', '富气机组', j(3600, 30), 0.15, 1.20, j(38, 0.5), j(135, 1), '', j(640, 5), 7700],
  ],
  '单价': [
    ['能源介质', '时段', '单价', '计价单位'],
    ['电', '峰', 0.98, 'kWh'],
    ['电', '平', 0.62, 'kWh'],
    ['电', '谷', 0.31, 'kWh'],
    ['电', '加权', 0.64, 'kWh'],
  ],
});

console.log(JSON.stringify({ ok: true, out, seed, files: fs.readdirSync(out).filter((f) => f.endsWith('.xlsx')) }));
