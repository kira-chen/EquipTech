const TYPE_PATTERNS = [
  ['电机', /电机|马达|电动机/],
  ['压缩机', /压缩机|空压|空气压缩|风机|鼓风|引风|增压机/],
  ['离心泵', /泵/],
  ['换热器', /换热器|冷却器|加热器|再沸器|冷凝器|空冷/],
  ['塔器容器', /塔|罐|容器|分离器|缓冲|储槽/],
  ['阀门', /阀/],
  ['管道', /管道|管线|管廊/],
];
function typeOf(name) {
  const s = String(name || '');
  for (const [t, re] of TYPE_PATTERNS) if (re.test(s)) return t;
  return '通用';
}
function observeOf(name) { return OBSERVE[typeOf(name)] || OBSERVE['通用']; }

