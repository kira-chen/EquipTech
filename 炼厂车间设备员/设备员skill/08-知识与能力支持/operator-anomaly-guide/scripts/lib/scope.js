/** 校验一条处置动作，返回 {ok, ruleId, reason, suggestion} */
function checkAction(text) {
  const s = String(text || '');
  for (const [id, re, reason] of OUT_OF_SCOPE) {
    if (re.test(s)) {
      return { ok: false, ruleId: id, reason, original: s, suggestion: '停止操作并立即上报，等待专业人员处理' };
    }
  }
  return { ok: true, ruleId: null, reason: null, original: s, suggestion: null };
}

/** 批量校验 */
function checkAll(actions) {
  const kept = [], blocked = [];
  for (const a of actions) {
    const r = checkAction(a);
    if (r.ok) kept.push(a); else blocked.push(r);
  }
  return { kept, blocked };
}

