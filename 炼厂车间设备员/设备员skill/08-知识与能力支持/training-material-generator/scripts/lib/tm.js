const QUESTION_TYPES = ['单选', '多选', '判断', '简答'];
function normTypes(v, warnings) {
  if (!v) return QUESTION_TYPES.slice();
  const out = [];
  for (const raw of String(v).split(/[,，、\s]+/).map((x) => x.trim()).filter(Boolean)) {
    const t = raw.replace(/题$/, '');
    const hit = QUESTION_TYPES.find((x) => x === t);
    if (hit) { if (!out.includes(hit)) out.push(hit); }
    else if (warnings) warnings.push(`题型「${raw}」无法识别，已忽略（可用：${QUESTION_TYPES.join('、')}）`);
  }
  return out;
}

