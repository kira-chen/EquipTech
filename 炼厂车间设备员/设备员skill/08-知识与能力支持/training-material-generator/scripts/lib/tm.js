/**
 * 判断题否定式改写：在原句上加否定词，**不改任何数值**；无可改写点返回 null（则只出肯定式）。
 * 返回 {text, rule}；调用方须校验改写前后数字序列一致。
 */
const NEGATE_RULES = [
  // 只改情态/比较词，避开复合词（应力、有效值、可靠、会议…），数字一律不碰
  ['J1', /不得/, '可以'],
  ['J2', /不应(?![力急])/, '应'],
  ['J3', /不宜/, '宜'],
  ['J4', /不需要|无需|不必/, '必须'],
  ['J15', /不(大于|超过|高于)/, '可以$1'],
  ['J16', /不(小于|低于|少于)/, '可以$1'],
  ['J5', /必须|(?<!必)须/, '无需'],
  ['J6', /应当|应该|(?<![反响对相适供])应(?![力急用变])/, '无需'],
  ['J7', /需要/, '不需要'],
  ['J8', /不能/, '可以'],
  ['J9', /可以|能够/, '不能'],
  ['J10', /不会/, '会'],
  ['J11', /(?<![机社学体])会(?!议)/, '不会'],
  ['J12', /(?<!可)靠(?!近)/, '不靠'],
  ['J13', /(?<![但还或就总只不])是(?!否)/, '不是'],
  ['J14', /(?<![所含具没])有(?![效无关])/, '没有'],
];
function negateStatement(text) {
  const s = String(text || '');
  for (const [rule, re, rep] of NEGATE_RULES) {
    if (re.test(s)) return { text: s.replace(re, rep), rule };
  }
  return null;
}
