/* ============================ 一、数值识别 ============================ */

/** 单位词表：命中即认为该文本承载「厂内规定的具体数值」 */
const UNIT_WORDS = [
  'N·m', 'N.m', 'Nm', 'kN', 'MPa', 'kPa', 'Pa', 'bar', 'kgf',
  'mm/s', 'μm', 'um', 'mm', 'cm', 'm3/h', 'm³/h', 't/h', 'kg',
  '℃', '°C', 'K/h', 'kW', 'kV', 'V', 'A', 'Hz', 'rpm', 'r/min',
  'ppm', 'mg/L', '%', '倍', '级', '°',
];
const UNIT_RE = new RegExp(
  '\\d+(?:\\.\\d+)?\\s*(?:' +
  UNIT_WORDS.map((u) => u.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|') +
  ')', 'i');
/** 周期型数值：「每 500 小时」「3 个月一次」「12 个月」 */
const PERIOD_RE = /\d+(?:\.\d+)?\s*(?:小时|h\b|天|日|周|个?月|季度|年)/i;
/** 区间型数值：「0.05~0.10」「不低于 0.3」「不大于 75」 */
const RANGE_RE = /\d+(?:\.\d+)?\s*[~～\-—至]\s*\d+(?:\.\d+)?|(?:不?(?:低于|高于|大于|小于|超过|少于)|≥|≤|＞|＜|>|<)\s*\d+(?:\.\d+)?/;

/** 该文本是否含具体技术数值（纯序号、纯年份、题号不算） */
function hasNumericValue(text) {
  const s = String(text || '');
  // 先剔掉明显的非技术数值：条款号「第3.2条」、纯编号「A-1」、年份
  const cleaned = s
    .replace(/第\s*[\d.]+\s*条/g, '')
    .replace(/[A-Za-z]-\d+/g, '')
    .replace(/(19|20)\d{2}\s*年(?!\s*一?次)/g, '')
    .replace(/\d+\s*[、.)）]/g, '');   // 题号 / 选项号
  return UNIT_RE.test(cleaned) || PERIOD_RE.test(cleaned) || RANGE_RE.test(cleaned);
}

