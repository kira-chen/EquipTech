#!/usr/bin/env node
'use strict';
/**
 * 生成参数趋势样例（可再生）。用法：node scripts/make-sample.js --out <dir> [--seed <n>]
 * 主样例 sample-trend.xlsx 恒：7 条参数序列、2 条已越限（1 条越高高报 HH、1 条越高报 H）、2 条趋势恶化、
 *   1 条只有 2 期（数据不足）、1 条含无法解析的数值、1 组采集时间重复、1 列带单位数值（℃ 后缀）。
 * sample-dcs-wide.xlsx：DCS/SAP 风格列名（功能位置、功能位置描述、仪表位号、参数名称）的宽表（一列一期），
 *   恒 3 条序列：1 条趋势恶化、1 条稳定、1 条数据不足（宽表空格=未测）。
 * seed 变数值抖动变，结论不变。
 */
const fs = require('fs');
const path = require('path');
const { writeXlsx } = require('./lib/xlsx-lite');
const C = require('./lib/common');

const a = C.parseArgs(process.argv.slice(2), ['out', 'seed'], []);
// 默认输出到演示样例目录：仓库内在 炼厂车间设备员/演示case/<分类>/<技能>/，开发包内在技能目录 examples/
const skillsRoot = path.resolve(__dirname, '../../..');
const caseDir = path.basename(skillsRoot) === '设备员skill' ? path.join(skillsRoot, '..', '演示case', path.relative(skillsRoot, path.resolve(__dirname, '..'))) : path.join(__dirname, '..', 'examples');
const out = a.out || caseDir;
const seed = a.seed ? Number(a.seed) : 1;
let s = seed * 7919 + 13;
const rnd = () => ((s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
/** 小幅抖动：幅度受控，不改变越限/恶化/稳定的结论 */
const j = (base, amp) => Number((base + (rnd() - 0.5) * 2 * amp).toFixed(2));

fs.mkdirSync(out, { recursive: true });

const days = ['2026-09-01', '2026-09-04', '2026-09-07', '2026-09-10', '2026-09-13', '2026-09-16', '2026-09-19'];
const rows = [['设备位号', '设备名称', '参数名', '采集时间', '数值', '单位']];

// P-1101A 振动：4.2 → 7.4 稳定上升，高报 9.0，未越限但会到限 → 趋势恶化
days.forEach((d, i) => rows.push(['P-1101A', '常压塔顶回流泵A', '振动速度', `${d} 08:00`, j(4.2 + i * 0.52, 0.06), 'mm/s']));
// P-1101A 轴承温度：已越高报（高报 75 / 高高报 85）；第 5 期带单位后缀「℃」，makeNum 剥离单位取数
days.forEach((d, i) => {
  const v = j(72 + i * 1.3, 0.3);
  rows.push(['P-1101A', '常压塔顶回流泵A', '轴承温度', `${d} 08:00`, i === 4 ? `${v}℃` : v, '℃']);
});
// P-1101B 振动：平稳，2.8 上下 → 稳定
days.forEach((d, i) => rows.push(['P-1101B', '常压塔顶回流泵B', '振动速度', `${d} 08:00`, j(2.8, 0.12), 'mm/s']));
// P-1102A 出口压力：下降趋势，只有高报 → 方向不对，不预测到限时间
days.forEach((d, i) => rows.push(['P-1102A', '常压渣油泵A', '出口压力', `${d} 08:00`, j(1.62 - i * 0.03, 0.01), 'MPa']));
// K-1201 电机电流：上升 → 趋势恶化；含 1 个无法解析的数值 + 1 组采集时间重复
days.forEach((d, i) => {
  const v = i === 3 ? '未记录' : j(118 + i * 2.6, 0.5);
  rows.push(['K-1201', '空压机', '电机电流', `${d} 08:00`, v, 'A']);
});
rows.push(['K-1201', '空压机', '电机电流', `${days[6]} 08:00`, j(136, 0.5), 'A']);   // 与末期时间重复
// M-1501 振动：只有 2 期 → 数据不足，不算趋势不预测
rows.push(['M-1501', '鼓风机电机', '振动速度', '2026-09-10 08:00', j(3.1, 0.1), 'mm/s']);
rows.push(['M-1501', '鼓风机电机', '振动速度', '2026-09-19 08:00', j(5.8, 0.1), 'mm/s']);
// E-1301 电机绕组温度：已越高高报（高报 120 / 高高报 130，最新约 133）
days.forEach((d, i) => rows.push(['E-1301', '原料油泵电机', '绕组温度', `${d} 08:00`, j(112 + i * 3.5, 0.4), '℃']));
rows.push(['合计', '', '', '', '', '']);

writeXlsx(path.join(out, 'sample-trend.xlsx'), {
  '参数记录': rows,
  '报警限值': [
    ['设备位号', '参数名', '高报', '高高报', '低报', '低低报', '单位'],
    ['P-1101A', '振动速度', 9.0, 11.2, '', '', 'mm/s'],
    ['P-1101A', '轴承温度', 75, 85, '', '', '℃'],
    ['P-1101B', '振动速度', 9.0, 11.2, '', '', 'mm/s'],
    ['P-1102A', '出口压力', 2.0, '', '', '', 'MPa'],
    ['K-1201', '电机电流', 165, 180, '', '', 'A'],
    ['M-1501', '振动速度', 11.2, '', '', '', 'mm/s'],
    ['E-1301', '绕组温度', 120, 130, '', '', '℃'],
  ],
});

// 宽表 + DCS/SAP 风格列名：功能位置 / 功能位置描述 / 仪表位号 / 参数名称 / 工程单位 / 一列一期
const wide = [
  ['某装置 DCS 趋势导出（示例）'],
  ['功能位置', '功能位置描述', '仪表位号', '参数名称', '工程单位', ...days],
  // 上升趋势 → 恶化（高报 85）
  ['P-2101A', '加氢进料泵A', 'TI-21011', '轴承温度', '℃', ...days.map((d, i) => j(62 + i * 2.1, 0.3))],
  // 平稳 → 稳定
  ['P-2101B', '加氢进料泵B', 'TI-21012', '轴承温度', '℃', ...days.map(() => j(58, 0.4))],
  // 只有 2 期有值（其余空格=未测）→ 数据不足
  ['K-2201', '循环氢压缩机', 'VI-22011', '轴振动', 'μm', '', '', '', '', '', j(28, 0.5), j(31, 0.5)],
];
writeXlsx(path.join(out, 'sample-dcs-wide.xlsx'), {
  '趋势数据': wide,
  '报警限值': [
    ['仪表位号', '参数名称', 'H', 'HH', 'L', 'LL', '单位'],
    ['TI-21011', '轴承温度', 85, 95, '', '', '℃'],
    ['TI-21012', '轴承温度', 85, 95, '', '', '℃'],
    ['VI-22011', '轴振动', 50, 80, '', '', 'μm'],
  ],
});

// 变体：无限值表 → 只算趋势不判越限
writeXlsx(path.join(out, 'sample-no-limit.xlsx'), {
  '参数记录': [
    ['设备位号', '设备名称', '参数名', '采集时间', '数值', '单位'],
    ...days.map((d, i) => ['P-2101', '加氢进料泵', '振动速度', `${d} 08:00`, j(3.5 + i * 0.4, 0.08), 'mm/s']),
  ],
});

// 变体：全部只有 2 期 → 全部数据不足
writeXlsx(path.join(out, 'sample-two-points.xlsx'), {
  '参数记录': [
    ['设备位号', '参数名', '采集时间', '数值', '单位'],
    ['P-3101', '振动速度', '2026-09-10 08:00', j(3.0, 0.1), 'mm/s'],
    ['P-3101', '振动速度', '2026-09-19 08:00', j(8.6, 0.1), 'mm/s'],
  ],
  '报警限值': [['设备位号', '参数名', '报警上限', '单位'], ['P-3101', '振动速度', 9.0, 'mm/s']],
});

console.log(JSON.stringify({ ok: true, out, seed, files: fs.readdirSync(out).filter((f) => f.endsWith('.xlsx')) }));
