#!/usr/bin/env node
'use strict';
/**
 * 生成运行小时样例（可再生）。用法：node scripts/make-sample.js --out <dir> [--seed <n>]
 * 主样例恒：6 台设备、1 条只有开机无停机、1 组区间重叠、1 处正常停机间隔、
 *          2 项超阈值（K-1201 运行小时、P-1101A 启停次数）、2 项接近阈值（P-1101B 轴承带期初累计、K-1201 大检修日历周期）、
 *          2 项未判定（P-1102A 累计不可算、M-1501 联轴器阈值类型为空）。
 * 变体：无阈值表 / 运行记录形式 / SAP PM 导出列名 / 运行状态记录（时序）。
 */
const fs = require('fs');
const path = require('path');
const { writeXlsx } = require('./lib/xlsx-lite');
const C = require('./lib/common');

const a = C.parseArgs(process.argv.slice(2), ['out', 'seed'], []);
const out = a.out || path.join(__dirname, '..', 'examples');
const seed = a.seed ? Number(a.seed) : 1;
let s = seed * 7919 + 13;
const rnd = () => ((s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
const hh = (lo, hi) => String(Math.floor(lo + rnd() * (hi - lo))).padStart(2, '0');
const between = (lo, hi) => Math.floor(lo + rnd() * (hi - lo));

fs.mkdirSync(out, { recursive: true });

writeXlsx(path.join(out, 'sample-runtime.xlsx'), {
  '启停记录': [
    ['位号', '设备名称', '开机时间', '停机时间'],
    // K-1201 压缩机：连续运行，本期超运行小时阈值
    ['K-1201', '空压机', `2026-09-01 ${hh(6, 9)}:00`, `2026-09-10 ${hh(14, 18)}:00`],
    ['K-1201', '空压机', `2026-09-10 ${hh(18, 20)}:00`, `2026-09-20 ${hh(8, 12)}:00`],
    // P-1101A：多次启停，超启停次数阈值
    ['P-1101A', '常压塔顶回流泵A', '2026-09-02 08:00', '2026-09-04 16:00'],
    ['P-1101A', '常压塔顶回流泵A', '2026-09-05 08:00', '2026-09-07 16:00'],
    ['P-1101A', '常压塔顶回流泵A', '2026-09-08 08:00', '2026-09-10 16:00'],
    ['P-1101A', '常压塔顶回流泵A', '2026-09-11 08:00', '2026-09-13 16:00'],
    ['P-1101A', '常压塔顶回流泵A', '2026-09-14 08:00', '2026-09-16 16:00'],
    // P-1101B：正常运行，带期初累计后接近轴承阈值
    ['P-1101B', '常压塔顶回流泵B', '2026-09-01 08:00', '2026-09-15 08:00'],
    // P-1102A：只有开机无停机（不配对）
    ['P-1102A', '常压渣油泵A', '2026-09-12 09:00', ''],
    // P-1102B：区间重叠
    ['P-1102B', '常压渣油泵B', '2026-09-01 08:00', '2026-09-10 08:00'],
    ['P-1102B', '常压渣油泵B', '2026-09-08 08:00', '2026-09-15 08:00'],
    // M-1501：正常停机间隔（两段之间停了 3 天）
    ['M-1501', '鼓风机电机', '2026-09-01 08:00', '2026-09-05 08:00'],
    ['M-1501', '鼓风机电机', '2026-09-08 08:00', '2026-09-12 08:00'],
  ],
  '阈值表': [
    ['位号', '部件', '阈值类型', '阈值', '上次归零日期', '期初累计小时'],
    ['K-1201', '机组', '运行小时', 400, '2026-09-01', 0],
    ['K-1201', '机组', '大检修周期（年）', 3, '2023-11-01', ''],
    ['P-1101A', '整机', '启停次数', 4, '2026-09-01', ''],
    ['P-1101B', '轴承', '运行小时', 8000, '2026-01-01', 7500 + between(0, 100)],
    ['P-1102A', '机械密封', '运行小时', 6000, '2026-01-01', 3200],
    ['M-1501', '电机', '运行小时', 5000, '2026-01-01', 1800 + between(0, 50)],
    ['M-1501', '联轴器', '', 3000, '2026-01-01', ''],
  ],
});

// 变体：无阈值表
writeXlsx(path.join(out, 'sample-no-threshold.xlsx'), {
  '启停记录': [
    ['位号', '设备名称', '开机时间', '停机时间'],
    ['P-2101', '加氢进料泵', '2026-09-01 08:00', '2026-09-10 08:00'],
  ],
});

// 变体：运行记录形式（非启停），运行时长带单位
writeXlsx(path.join(out, 'sample-run-hours.xlsx'), {
  '运行记录': [
    ['位号', '设备名称', '运行时长'],
    ['P-3101', '循环油泵', '168h'],
    ['P-3102', '备用泵', '未记录'],
  ],
  '阈值表': [['位号', '阈值类型', '阈值', '期初累计小时'], ['P-3101', '运行小时', '200h', 0], ['P-3102', '运行小时', 200, 0]],
});

// 变体：SAP PM / EM 导出列名（功能位置 + 设备流水号 + 设备描述），阈值表用"上次大检修日期 / 上次大检修后累计"
writeXlsx(path.join(out, 'sample-sap-export.xlsx'), {
  '开停机记录': [
    ['功能位置', '设备', '设备描述', '启动时间', '停止时间'],
    ['C-2301', '10012345', '催化主风机', '2026-09-01 00:00', '2026-09-21 00:00'],
    ['P-2302A', '10012388', '油浆泵A', '2026-09-01 08:00', '2026-09-11 08:00'],
    ['P-2302A', '10012388', '油浆泵A', '2026-09-12 08:00', '2026-09-20 08:00'],
  ],
  '检修周期': [
    ['功能位置', '部件', '周期类型', '检修周期', '上次大检修日期', '上次大检修后累计'],
    ['C-2301', '机组', '运行小时', '24000h', '2023-11-15', 23000 + between(0, 300)],
    ['C-2301', '机组', '日历周期（年）', '3年', '2023-11-15', ''],
    ['P-2302A', '机械密封', '运行小时', 8000, '2026-03-01', 2600],
  ],
});

// 变体：运行状态记录（时序，一行一个状态点）
writeXlsx(path.join(out, 'sample-status-series.xlsx'), {
  '运行状态记录': [
    ['位号', '设备名称', '时间', '运行状态'],
    ['P-4101A', '加氢循环泵A', '2026-09-01 08:00', '运行'],
    ['P-4101A', '加氢循环泵A', '2026-09-05 08:00', '运行'],
    ['P-4101A', '加氢循环泵A', '2026-09-08 08:00', '停机'],
    ['P-4101A', '加氢循环泵A', '2026-09-10 08:00', '运行'],
    ['P-4101A', '加氢循环泵A', '2026-09-12 08:00', '备用'],
    ['P-4101B', '加氢循环泵B', '2026-09-08 08:00', '运行'],
  ],
  '阈值表': [['位号', '阈值类型', '阈值', '期初累计小时'], ['P-4101A', '运行小时', 240, 0], ['P-4101B', '运行小时', 8000, 5000]],
});

console.log(JSON.stringify({ ok: true, out, seed, files: fs.readdirSync(out).filter((f) => f.endsWith('.xlsx')) }));
