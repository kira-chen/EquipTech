#!/usr/bin/env node
'use strict';
/**
 * 生成备用设备切换盘车样例输入（可再生）。用法：node scripts/make-sample.js --out <dir> [--seed <n>] [--date <YYYY-MM-DD>]
 * 主样例恒为：2 项切换逾期、1 项切换临期、2 项盘车逾期、2 项盘车临期、
 *             3 项无法判定、2 行主备无法配对、2 台长期未切换（2 倍切换周期口径）、1 台备机检修中、
 *             5 个机组当前主用由切换记录推导（其中 P-1101、P-1102 与台账相反）。
 * 列名：主样例用车间台账常见列名（含机组号、备机状态、切至位号）；导出变体用 EM/SAP 导出列名（功能位置、设备描述、装置名称）。
 */
const fs = require('fs');
const path = require('path');
const { writeXlsx } = require('./lib/xlsx-lite');
const C = require('./lib/common');

const a = C.parseArgs(process.argv.slice(2), ['out', 'seed', 'date'], []);
// 默认输出到演示样例目录：仓库内在 炼厂车间设备员/演示case/<分类>/<技能>/，开发包内在技能目录 examples/
const skillsRoot = path.resolve(__dirname, '../../..');
const caseDir = path.basename(skillsRoot) === '设备员skill' ? path.join(skillsRoot, '..', '演示case', path.relative(skillsRoot, path.resolve(__dirname, '..'))) : path.join(__dirname, '..', 'examples');
const out = a.out || caseDir;
const date = a.date || '2026-09-21';
const seed = a.seed ? Number(a.seed) : 1;
let s = seed * 7919 + 13;
const rnd = () => ((s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
/** 在 ±d 天内抖动，但不跨越分档边界（调用处已留足余量） */
const jd = (n, d = 2) => n + Math.round((rnd() - 0.5) * 2 * d);
const back = (n) => C.addDays(date, -n);   // 基准日往前 n 天

fs.mkdirSync(out, { recursive: true });

const LED_HDR = ['机组号', '主用位号', '备用位号', '设备名称', '装置', '备机状态', '切换周期', '盘车周期', '试运周期', '上次切换日期', '上次盘车日期', '上次试运日期'];
const REC_HDR = ['日期', '位号', '作业类型', '切至位号', '执行人', '备注'];

const d1101 = back(jd(130, 5)), d1102 = back(jd(200, 5)), d1103 = back(88), d1201 = back(jd(30, 5));
const d1301 = back(jd(20, 4)), d1302 = back(jd(10, 3));
const d2101 = back(jd(200, 5)), d2101t = back(jd(2, 1));
// ---- 主样例：备用设备台账 + 切换盘车记录
const ledger = [
  LED_HDR,
  // 1) 切换逾期（上次切换 130 天前，周期 1 个月=30 天）+ 长期未切换（≥2×30=60 天）；当前主用由记录推导为 B
  ['P-1101', 'P-1101A', 'P-1101B', '常压塔顶回流泵', '常减压装置', '备用', '1个月', '7天', '1个月', d1101, back(jd(2, 1)), back(jd(10, 3))],
  // 2) 切换逾期（上次切换 200 天前，周期 2 个月=60 天）+ 长期未切换（≥120 天）；当前主用由记录推导为 B
  ['P-1102', 'P-1102A', 'P-1102B', '常压渣油泵', '常减压装置', '备用', '2个月', '每周', '', d1102, back(jd(2, 1)), ''],
  // 3) 切换临期（周期 90 天，上次 88 天前 → 剩 2 天，lead 3）
  ['P-1103', 'P-1103A', 'P-1103B', '常压侧线泵', '常减压装置', '备用', '90天', '14天', '', d1103, back(jd(5, 2)), ''],
  // 4) 盘车逾期（周期 7 天，上次 20 天前）；切换周期内
  ['P-1201', 'P-1201A', 'P-1201B', '减压塔底泵', '常减压装置', '备用', '6个月', '7天', '', d1201, back(jd(20, 3)), ''],
  // 5) 盘车逾期（周期 14 天，上次 40 天前）；切换周期内
  ['K-1401', 'K-1401A', 'K-1401B', '富气压缩机油泵', '气分装置', '备用', '1年', '14天', '3个月', back(jd(60, 5)), back(jd(40, 4)), back(jd(40, 5))],
  // 6) 盘车临期（周期 14 天，上次 12 天前 → 剩 2 天）；切换周期内
  ['P-1301', 'P-1301A', 'P-1301B', '污水提升泵', '公用工程', '备用', '3个月', '14天', '', d1301, back(12), ''],
  // 7) 盘车临期：班次级周期「每班」，上次盘车为当日 → 本日内按班次到期；切换周期内
  ['P-1302', 'P-1302A', 'P-1302B', '循环水补水泵', '公用工程', '备用', '3个月', '每班', '', d1302, date, ''],
  // 8) 无法判定：切换周期为空（绝不按一月一次默认）
  ['P-1401', 'P-1401A', 'P-1401B', '加氢进料泵', '加氢装置', '备用', '', '7天', '', back(jd(150, 5)), back(jd(2, 1)), ''],
  // 9) 无法判定：上次盘车日期为空
  ['P-1402', 'P-1402A', 'P-1402B', '循环氢压缩机油泵', '加氢装置', '备用', '3个月', '7天', '', back(jd(20, 4)), '', ''],
  // 10) 无法判定：切换周期写法无法解析（「随机组检修」）
  ['P-1403', 'P-1403A', 'P-1403B', '反应进料泵', '加氢装置', '备用', '随机组检修', '14天', '', back(jd(20, 4)), back(jd(5, 2)), ''],
  // 11) 主备无法配对：备用位号为空（绝不猜测配对）
  ['P-1501', 'P-1501A', '', '延迟焦化给水泵', '焦化装置', '备用', '3个月', '7天', '', back(jd(40, 5)), back(jd(3, 1)), ''],
  // 12) 主备无法配对：主用位号为空
  ['P-1502', '', 'P-1502B', '焦化冷焦水泵', '焦化装置', '备用', '3个月', '7天', '', back(jd(40, 5)), back(jd(3, 1)), ''],
  // 13) 备机检修中：切换已严重逾期，但不进到期清单，单列
  ['P-1601', 'P-1601A', 'P-1601B', '焦化放空泵', '焦化装置', '检修中', '1个月', '7天', '', back(jd(150, 5)), back(jd(30, 3)), ''],
];
const records = [
  REC_HDR,
  [d1101, 'P-1101A', '主备切换', 'P-1101B', '张工', '切至B泵'],
  [d1102, 'P-1102A', '主备切换', 'P-1102B', '王工', ''],
  [d1103, 'P-1103A', '主备切换', 'P-1103A', '张工', '切回A泵'],
  [d1201, 'P-1201A', '主备切换', '', '李工', '未填切换方向'],
  [d1302, 'P-1302A', '主备切换', 'P-1302A', '张工', ''],
  [d1301, 'P-1301A', '主备切换', 'P-1301A', '李工', ''],
  [back(jd(40, 4)), 'K-1401B', '试运', '', '王工', '备机试运 30 分钟'],
  [back(jd(5, 2)), 'P-9999', '盘车', '', '赵工', '台账中无此位号'],   // 台账无对应机组 → 不计入执行率
  [back(jd(6, 2)), 'P-1302B', '检查', '', '赵工', '作业类型无法归类'], // 类型无法归类 → 不计入执行率
];
// 盘车按周期补足记录，使执行率统计有可比基数（不影响到期分档）
const turningPlan = [
  ['P-1101A', 7, 2], ['P-1102A', 7, 3], ['P-1103B', 14, 5],
  ['P-1201B', 7, 20], ['K-1401B', 14, 40], ['P-1301B', 14, 12],
];
for (const [tag, period, last] of turningPlan) {
  for (let d = last; d <= 175; d += period) records.push([back(d), tag, '盘车', '', '当班', '']);
}
writeXlsx(path.join(out, `sample-rotation-${date}.xlsx`), {
  '备用设备台账': ledger,
  '切换盘车记录': records,
});

// ---- 变体：仅台账（无切换盘车记录 → 不统计执行率；当前主用按台账）
writeXlsx(path.join(out, `sample-ledger-only-${date}.xlsx`), { '备用设备台账': ledger });

// ---- 变体：EM/SAP 导出风格（标题行 + 系统列名 + 合计行 + 周期写法多样 + 无备机状态列）
writeXlsx(path.join(out, 'sample-rotation-export.xlsx'), {
  '备用设备台账': [
    ['某某炼化厂 EM 备用设备定期切换台账导出'],
    [],
    ['机组编号', '主用', '备用', '设备描述', '装置名称', '倒泵周期', '盘车间隔', '试运转周期', '上次切换', '上次盘车', '上次试运'],
    ['P-2101', 'P-2101A', 'P-2101B', '柴油加氢进料泵', '柴油加氢装置', '180', '7天', '', d2101, d2101t, ''],
    ['P-2102', 'P-2102A', 'P-2102B', '循环氢压缩机油泵', '柴油加氢装置', '半年', '每2小时', '', back(jd(30, 4)), back(1), ''],
    ['P-2103', 'P-2103A', 'P-2103A', '反应进料泵', '柴油加氢装置', '1季', '7天', '', back(jd(30, 4)), back(jd(3, 1)), ''],  // 主备同位号 → 无法配对
    ['合计', '', '', '', '', '', '', '', '', '', ''],
  ],
  '切换盘车记录': [
    ['执行日期', '功能位置', '工作类型', '切换后主用', '操作人', '说明'],
    [d2101, 'P-2101A', '倒泵', 'P-2101B', '王工', ''],
    [d2101t, 'P-2101B', '盘车', '', '王工', ''],
  ],
});

console.log(JSON.stringify({ ok: true, out, date, seed, files: fs.readdirSync(out).filter((f) => f.endsWith('.xlsx')) }));
