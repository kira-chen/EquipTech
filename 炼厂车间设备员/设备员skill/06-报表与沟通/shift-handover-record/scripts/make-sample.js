#!/usr/bin/env node
'use strict';
/**
 * 生成设备员值班与工作交接记录样例输入（可再生）。用法：node scripts/make-sample.js --out <dir> [--seed <n>] [--date <YYYY-MM-DD>]
 * 口径：车间设备员常白班，交接的是 值班 / 休假 / 调岗 工作交接，不是操作班组交接班。
 * 主样例结论恒定：3 项状态变化、5 项异常处理（2 已闭环）、2 台在修、1 项类型未归类、1 项状态未判定、5 项未完成（配上次交接 --prev 后 6 项）。
 * 上次交接样例恒含 3 条遗留：1 条本次已闭环、1 条本次跟进未闭环、1 条本次完全无记录（必结转）。
 * 另有：极简变体（缺责任人/缺在修表）、EM/SAP 导出风格变体（标题行 + 功能位置/设备描述/订单 列名 + 合计行）。
 */
const fs = require('fs');
const path = require('path');
const { writeXlsx } = require('./lib/xlsx-lite');
const C = require('./lib/common');

const a = C.parseArgs(process.argv.slice(2), ['out', 'seed', 'date'], []);
const out = a.out || path.join(__dirname, '..', 'examples');
const date = a.date || '2026-09-21';
const prevDate = C.addDays(date, -1);
const seed = a.seed ? Number(a.seed) : 1;
let s = seed * 7919 + 13;
const rnd = () => ((s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
const jitter = (v, p = 0.06) => Number((v * (1 + (rnd() - 0.5) * 2 * p)).toFixed(1));

fs.mkdirSync(out, { recursive: true });

